"""Summarize private multi-city cohorts into an allowlisted aggregate source audit."""

import argparse
import csv
import gzip
import hashlib
import json
import math
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "pipeline"))

from market_sources import archive_path, verify_archive

MANIFEST = ROOT / "specs/003-multi-city-research/source-manifest.json"
LATITUDE_CENTERS = {
    "clark-county-nv": 36.2,
    "new-york-city": 40.7,
    "los-angeles": 34.1,
    "nashville": 36.15,
}
EARTH_KM = 6371.0088


def summarize(market, source, root=ROOT):
    root = Path(root)
    source_path = archive_path(market, source, root)
    header = json.loads(MANIFEST.read_text(encoding="utf-8"))["header_sha256"]
    verify_archive(source_path, source, header)
    directory = root / "data/research/multi-city" / market / source["snapshot_date"]
    audit = json.loads((directory / "audit.json").read_text(encoding="utf-8"))
    if audit["source"]["sha256"] != source["sha256"]:
        raise ValueError("Private audit source digest differs from pinned manifest")
    code_digest = hashlib.sha256(
        (root / "pipeline/market_normalize.py").read_bytes()
    ).hexdigest()
    if audit["normalizer_sha256"] != code_digest:
        raise ValueError("Private audit was generated by a different normalizer")
    blocks = Counter()
    lat_min, lat_max, lon_min, lon_max = 90.0, -90.0, 180.0, -180.0
    rows = 0
    with (directory / "normalized.jsonl").open(encoding="utf-8") as handle:
        for line in handle:
            row = json.loads(line)
            if (
                row["market_id"] != market
                or row["snapshot_date"] != source["snapshot_date"]
            ):
                raise ValueError("Private row market or snapshot mismatch")
            lat, lon = row["latitude"], row["longitude"]
            lat_min, lat_max = min(lat_min, lat), max(lat_max, lat)
            lon_min, lon_max = min(lon_min, lon), max(lon_max, lon)
            x = (
                EARTH_KM
                * math.cos(math.radians(LATITUDE_CENTERS[market]))
                * math.radians(lon)
            )
            y = EARTH_KM * math.radians(lat)
            blocks[(math.floor(x / 5), math.floor(y / 5))] += 1
            rows += 1
    if (
        rows != audit["included_rows"]
        or rows + audit["excluded_rows"] != audit["source_rows"]
    ):
        raise ValueError("Private cohort does not reconcile with audit")
    missing = Counter()
    with gzip.open(source_path, "rt", encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        fields = reader.fieldnames or []
        source_rows = 0
        for source_row in reader:
            source_rows += 1
            missing.update(field for field in fields if not source_row.get(field))
    if source_rows != audit["source_rows"]:
        raise ValueError("Source archive row count differs from private audit")
    status = audit["statuses"]
    return {
        "snapshot_date": source["snapshot_date"],
        "source_area": source["source_area"],
        "source_sha256": source["sha256"],
        "normalized_sha256": hashlib.sha256(
            (directory / "normalized.jsonl").read_bytes()
        ).hexdigest(),
        "normalizer_sha256": audit["normalizer_sha256"],
        "normalization_rules_version": audit["normalization_rules_version"],
        "source_rows": audit["source_rows"],
        "source_field_missing_counts": {field: missing[field] for field in fields},
        "included_rows": rows,
        "exclusions": audit["first_failure_reasons"],
        "room_types_source": audit["room_types"],
        "unknown_property_labels": status.get("property_group:unknown", 0),
        "missing_overall_rating": status.get("review_scores_rating:missing", 0),
        "invalid_overall_rating": status.get("review_scores_rating:invalid", 0),
        "selected_field_statuses": status,
        "asking_price_usd_included": audit["included_price_usd"],
        "source_coordinate_extent": {
            "lat_min": lat_min,
            "lat_max": lat_max,
            "lon_min": lon_min,
            "lon_max": lon_max,
        },
        "candidate_5km_blocks": len(blocks),
        "candidate_5km_blocks_with_at_least_20_rows": sum(
            n >= 20 for n in blocks.values()
        ),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    path = Path(args.output).resolve()
    if path != (ROOT / "specs/003-multi-city-research/source-audit.json").resolve():
        parser.error("Aggregate output path must be the reviewed source-audit.json")
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    result = {
        "schema_version": 1,
        "source_manifest_sha256": hashlib.sha256(MANIFEST.read_bytes()).hexdigest(),
        "limitations": [
            "Source-row audit; no model training or performance evidence",
            "Missing asking prices cause market-dependent supervised cohort selection",
            "Approximate coordinates do not establish parcel locations or physical independence",
            "Candidate 5 km block counts are support diagnostics, not frozen partitions",
        ],
        "markets": {
            market: summarize(market, source)
            for market, source in sorted(manifest["markets"].items())
        },
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    part = path.with_suffix(".json.part")
    try:
        part.write_text(
            json.dumps(result, sort_keys=True, indent=2, allow_nan=False) + "\n",
            encoding="utf-8",
        )
        part.replace(path)
    finally:
        part.unlink(missing_ok=True)
    print(f"Aggregate source audit: {len(result['markets'])} markets")


if __name__ == "__main__":
    main()
